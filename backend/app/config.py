from pydantic import model_validator
from pydantic_settings import BaseSettings


class Settings(BaseSettings):
    database_url: str = "postgresql+psycopg://connectflow:connectflow@postgres:5432/connectflow"
    redis_url: str = "redis://redis:6379/0"
    jwt_secret: str  # required: long random string
    cookie_secure: bool = False  # set true behind HTTPS
    session_hours: int = 24 * 7

    # WhatsApp gateway (OpenWA node running the Baileys engine)
    openwa_url: str = "http://openwa-wa:2785"
    openwa_key_file: str = "/openwa-data/.api-key"  # generated by OpenWA on first boot, mounted read-only
    openwa_webhook_secret: str  # HMAC secret OpenWA signs our webhooks with
    internal_webhook_url: str = "http://backend:8000/internal/wa-webhook"

    # Google sign-in (OAuth 2.0 authorization-code flow). Leave empty to disable the button.
    google_client_id: str = ""
    google_client_secret: str = ""
    public_app_url: str = "http://app.connectflow.localhost:8080"  # where users reach the app (used for the OAuth redirect URI)

    # Outgoing email (Mailpit locally; a real SMTP provider in production)
    resend_api_key: str = ""  # if set, email goes through Resend's HTTPS API instead of SMTP
    smtp_host: str = "mailpit"
    smtp_port: int = 1025
    smtp_user: str = ""
    smtp_password: str = ""
    smtp_from: str = "ConnectFlow <no-reply@connectflow.local>"

    # Customer webhooks may only target public internet hosts. Set true ONLY in local development to test against local receivers.
    webhook_allow_private: bool = False

    # AI (OpenAI-compatible chat API, DeepSeek by default) and web search for lead research
    ai_api_key: str = ""
    ai_base_url: str = "https://api.deepseek.com"
    ai_model: str = "deepseek-v4-pro"
    searxng_url: str = ""
    # Dev/test switches (default off): deterministic AI text, and a sender that marks messages sent without calling the gateway
    ai_fake: bool = False
    outreach_fake_send: bool = False

    # Security / abuse detection for the public API (see app/telemetry.py)
    sec_ip_rate_per_min: int = 60          # requests per minute per client IP, before the key is even looked up
    sec_fail_limit_5min: int = 20          # failed (401) attempts per IP in 5 minutes before that IP is blocked for the rest of the window
    sec_many_ips_24h: int = 5              # a key used from MORE than this many distinct IPs in 24 h is suspended
    sec_known_ips_before_alert: int = 3    # a new IP on a key that already has this many known IPs raises a warning
    sec_volume_floor: int = 50             # requests/hour that can raise a warning (or 10x the key's daily average, if higher)
    sec_volume_critical_floor: int = 200   # requests/hour that suspend the key (or 10x the daily average, if higher)
    sec_volume_mult: int = 10
    ai_global_daily_cap: int = 0           # AI calls per UTC day for the whole platform (circuit breaker); 0 = off

    # First platform admin (created on startup if missing)
    admin_email: str = ""
    admin_password: str = ""

    @model_validator(mode="after")
    def _production_sanity(self) -> "Settings":
        """With cookie_secure=true (HTTPS / production) refuse to boot with weak or placeholder secrets."""
        if self.cookie_secure:
            for name in ("jwt_secret", "openwa_webhook_secret"):
                v = getattr(self, name)
                if len(v) < 32 or "change" in v.lower() or "example" in v.lower():
                    raise ValueError(f"{name.upper()} is too weak for production: use at least 32 random characters")
            if self.webhook_allow_private:
                raise ValueError("WEBHOOK_ALLOW_PRIVATE must be false in production")
            if self.ai_fake or self.outreach_fake_send:
                raise ValueError("AI_FAKE / OUTREACH_FAKE_SEND are test switches and must be off in production")
        return self

    class Config:
        env_file = ".env"


settings = Settings()
