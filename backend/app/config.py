import base64

from typing import Any

from pydantic import field_validator, model_validator
from pydantic_settings import BaseSettings


class Settings(BaseSettings):
    database_url: str = "postgresql+psycopg://connectflow:connectflow@postgres:5432/connectflow"
    redis_url: str = "redis://redis:6379/0"
    jwt_secret: str  # required: long random string
    cookie_secure: bool = False  # set true behind HTTPS
    session_hours: int = 24 * 7

    # WhatsApp gateway (OpenWA node running the Baileys engine)
    openwa_url: str = "http://openwa-wa:2785"
    openwa_key_file: str = "/openwa-data/.api-key"  # generated by OpenWA on first boot, mounted read-only
    openwa_webhook_secret: str  # HMAC secret OpenWA signs our webhooks with
    internal_webhook_url: str = "http://backend:8000/internal/wa-webhook"

    # Google sign-in (OAuth 2.0 authorization-code flow). Leave empty to disable the button.
    google_client_id: str = ""
    google_client_secret: str = ""
    public_app_url: str = "http://app.connectflow.localhost:8080"  # where users reach the app (used for the OAuth redirect URI)

    # Outgoing email (Mailpit locally; a real SMTP provider in production)
    resend_api_key: str = ""  # if set, email goes through Resend's HTTPS API instead of SMTP
    smtp_host: str = "mailpit"
    smtp_port: int = 1025
    smtp_user: str = ""
    smtp_password: str = ""
    smtp_from: str = "ConnectFlow <no-reply@connectflow.local>"

    # Customer webhooks may only target public internet hosts. Set true ONLY in local development to test against local receivers.
    webhook_allow_private: bool = False

    # AI (OpenAI-compatible chat API, DeepSeek by default) and web search for lead research
    ai_api_key: str = ""
    ai_base_url: str = "https://api.deepseek.com"
    ai_model: str = "deepseek-v4-pro"
    searxng_url: str = ""
    # Dev/test switches (default off): deterministic AI text, and a sender that marks messages sent without calling the gateway
    ai_fake: bool = False
    outreach_fake_send: bool = False

    # Security / abuse detection for the public API (see app/telemetry.py)
    sec_ip_rate_per_min: int = 60          # requests per minute per client IP, before the key is even looked up
    sec_fail_limit_5min: int = 20          # failed (401) attempts per IP in 5 minutes before that IP is blocked for the rest of the window
    sec_many_ips_24h: int = 5              # a key used from MORE than this many distinct IPs in 24 h is suspended
    sec_known_ips_before_alert: int = 3    # a new IP on a key that already has this many known IPs raises a warning
    sec_volume_floor: int = 50             # requests/hour that can raise a warning (or 10x the key's daily average, if higher)
    sec_volume_critical_floor: int = 200   # requests/hour that suspend the key (or 10x the daily average, if higher)
    sec_volume_mult: int = 10
    ai_global_daily_cap: int = 0           # AI calls per UTC day for the whole platform (circuit breaker); 0 = off
    # AI cost accounting. Prices are USD per MILLION tokens and come from your provider's price page: 0 = unknown (the cost column then stays 0).
    ai_price_in_per_m: float = 0.0
    ai_price_out_per_m: float = 0.0
    ai_price_cached_per_m: float = 0.0
    ai_model_fast: str = ""                # optional cheaper model for extraction/classification-like calls (pick_website, extract_facts, follow-ups); empty = AI_MODEL
    ai_knowledge_max_chars: int = 8000     # the knowledge base is sent with EVERY call: cap what is injected (the profile still stores up to 20000)

    # Stripe billing. Leave STRIPE_SECRET_KEY empty to keep the manual upgrade-request flow.
    stripe_secret_key: str = ""
    stripe_webhook_secret: str = ""
    stripe_price_starter: str = ""         # optional price_... ids; without them Checkout uses inline USD prices from the plans table
    stripe_price_growth: str = ""
    stripe_api_base: str = "https://api.stripe.com"  # tests point this at a fake server

    # First platform admin (created on startup if missing)
    admin_email: str = ""
    admin_password: str = ""

    # Encryption at rest for webhook signing secrets and 2FA secrets (Fernet: urlsafe-base64 of 32 random bytes).
    # Empty = derive a key from JWT_SECRET (development only; production requires a dedicated key). See docs/SECRETS.md for rotation.
    encryption_key: str = ""
    encryption_key_previous: str = ""      # the old key while rotating (decrypt-only), removed after `python -m app.tools.reencrypt`

    # Two-factor authentication: None = required for platform admins exactly when COOKIE_SECURE=true (production)
    admin_2fa_required: bool | None = None

    # Media library storage (see docs/MEDIA.md). local = Docker volume at ASSETS_DIR; cloudinary = Cloudinary REST API (CLOUDINARY_URL=cloudinary://key:secret@cloud)
    storage_backend: str = "local"
    assets_dir: str = "/data/assets"
    cloudinary_url: str = ""
    cloudinary_api_base: str = "https://api.cloudinary.com/v1_1"   # tests point this at a fake server

    # Signup abuse controls
    disposable_email_allow: str = ""       # comma separated domains that are allowed even though they are on the disposable list
    turnstile_site_key: str = ""           # Cloudflare Turnstile (optional): both keys set = captcha on signup / forgot / login after failures
    turnstile_secret_key: str = ""

    @field_validator("admin_2fa_required", mode="before")
    @classmethod
    def _blank_is_default(cls, v: Any) -> Any:
        """`ADMIN_2FA_REQUIRED=` (empty) in .env means "use the default", not a parse error."""
        return None if isinstance(v, str) and not v.strip() else v

    @model_validator(mode="after")
    def _production_sanity(self) -> "Settings":
        """With cookie_secure=true (HTTPS / production) refuse to boot with weak or placeholder secrets."""
        if self.cookie_secure:
            for name in ("jwt_secret", "openwa_webhook_secret"):
                v = getattr(self, name)
                if len(v) < 32 or "change" in v.lower() or "example" in v.lower():
                    raise ValueError(f"{name.upper()} is too weak for production: use at least 32 random characters")
            if self.webhook_allow_private:
                raise ValueError("WEBHOOK_ALLOW_PRIVATE must be false in production")
            if self.ai_fake or self.outreach_fake_send:
                raise ValueError("AI_FAKE / OUTREACH_FAKE_SEND are test switches and must be off in production")
            if self.ai_global_daily_cap <= 0:
                raise ValueError("AI_GLOBAL_DAILY_CAP must be > 0 in production (the platform-wide circuit breaker for runaway AI spend; e.g. 5000)")
            if not self.encryption_key:
                raise ValueError("ENCRYPTION_KEY is required in production (generate with: python -c \"from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())\")")
        for name in ("encryption_key", "encryption_key_previous"):
            v = getattr(self, name)
            if v:
                try:  # (not imported from crypto.py: that module imports this one)
                    ok = len(base64.urlsafe_b64decode(v.encode())) == 32
                except Exception:  # noqa: BLE001
                    ok = False
                if not ok:
                    raise ValueError(f"{name.upper()} is not a valid Fernet key (urlsafe base64 of 32 bytes)")
        if self.storage_backend not in ("local", "cloudinary"):
            raise ValueError("STORAGE_BACKEND must be local or cloudinary")
        if self.storage_backend == "cloudinary" and not self.cloudinary_url.startswith("cloudinary://"):
            raise ValueError("STORAGE_BACKEND=cloudinary needs CLOUDINARY_URL=cloudinary://<api_key>:<api_secret>@<cloud_name>")
        if bool(self.turnstile_site_key) != bool(self.turnstile_secret_key):
            raise ValueError("Set both TURNSTILE_SITE_KEY and TURNSTILE_SECRET_KEY, or neither")
        return self

    class Config:
        env_file = ".env"
        extra = "ignore"  # a dev .env also holds compose-only keys (POSTGRES_PASSWORD, APP_HOST, ...): never crash on them


settings = Settings()  # type: ignore[call-arg]  # required fields (JWT_SECRET, ...) are read from the environment
